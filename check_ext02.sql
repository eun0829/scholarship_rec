-- ============================================================
-- 외부02(드림스폰) 저장 결과 확인용 쿼리 (조회만 합니다)
-- ============================================================

-- 1) 상태별 건수 / 사용 여부
SELECT   STATUS_CD, USE_YN, COUNT(*) CNT
FROM     SCHOLARSHIP_NOTICE
WHERE    SRC_CD = 'EXT02'
GROUP BY STATUS_CD, USE_YN
ORDER BY STATUS_CD, USE_YN;

-- 2) 공고 목록 (마감 빠른 순): 구분, 신청 방식, 신청기간, 요약
SELECT   SRC_ID, STATUS_CD, CATEGORY_CD, APPLY_TYPE_CD,
         TO_CHAR(APPLY_START, 'YYYY-MM-DD') APPLY_START, TO_CHAR(APPLY_END, 'YYYY-MM-DD') APPLY_END,
         SUBSTR(TITLE, 1, 40) TITLE
FROM     SCHOLARSHIP_NOTICE
WHERE    SRC_CD = 'EXT02' AND USE_YN = 'Y'
ORDER BY APPLY_END NULLS LAST, SRC_ID;

-- 3) 마감일을 어디서 얻었는지 (DETAIL / INFO_TABLE / NONE) - NONE 이나 D-day 추정은 확인 필요
SELECT   SRC_ID, SUBSTR(TITLE, 1, 30) TITLE,
         CASE WHEN DBMS_LOB.INSTR(SRC_FIELDS_JSON, '"source": "DETAIL"') > 0 THEN 'DETAIL'
              WHEN DBMS_LOB.INSTR(SRC_FIELDS_JSON, '"source": "INFO_TABLE"') > 0 THEN 'INFO_TABLE'
              ELSE 'NONE' END PERIOD_SOURCE,
         TO_CHAR(APPLY_END, 'YYYY-MM-DD') APPLY_END
FROM     SCHOLARSHIP_NOTICE
WHERE    SRC_CD = 'EXT02' AND SRC_FIELDS_JSON IS NOT NULL
ORDER BY PERIOD_SOURCE, APPLY_END;

-- 4) 특정 글의 출처 구조화 항목 (7개 항목) - :src_id 에 idx 입력
SELECT   DBMS_LOB.SUBSTR(SRC_FIELDS_JSON, 4000, 1) SRC_FIELDS_JSON
FROM     SCHOLARSHIP_NOTICE
WHERE    SRC_CD = 'EXT02' AND SRC_ID = :src_id;

-- 5) 검수 필요 사유 (마감일 불일치, D-day 추정, 접수방법 불일치 등)
SELECT   SRC_ID, DBMS_LOB.SUBSTR(UNCERTAIN_JSON, 4000, 1) REVIEW_JSON
FROM     SCHOLARSHIP_NOTICE
WHERE    SRC_CD = 'EXT02' AND STATUS_CD IN ('NEED_REVIEW', 'FAILED')
ORDER BY SRC_ID DESC;

-- 6) 첨부 처리 결과 (ZIP 은 내부 파일마다 한 행: FILE_SEQ '1-abc123.1' ...). 역할(ROLE_CD): GUIDE=공고문, FORM=양식
SELECT   SRC_ID, FILE_SEQ, ROLE_CD, STATUS_CD, EXTRACT_METHOD, TEXT_LEN,
         SUBSTR(ORG_FILE_NM, 1, 50) FILE_NM, SUBSTR(ERR_MSG, 1, 60) ERR_MSG
FROM     SCHOLARSHIP_NOTICE_FILE
WHERE    SRC_CD = 'EXT02'
ORDER BY SRC_ID DESC, FILE_SEQ;

-- 7) 첨부 분류별 건수와 추출 성공률 (guide_only 로 AI 에 보낼 만한 공고문이 얼마나 되는지 판단)
SELECT   ROLE_CD, STATUS_CD, COUNT(*) CNT
FROM     SCHOLARSHIP_NOTICE_FILE
WHERE    SRC_CD = 'EXT02'
GROUP BY ROLE_CD, STATUS_CD
ORDER BY ROLE_CD, STATUS_CD;
